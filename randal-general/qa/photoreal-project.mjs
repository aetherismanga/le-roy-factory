import assert from 'node:assert/strict';
import {buildGeneralPhotorealPrompt} from '../src/photoreal-project.js';
import {initialDraft,draftProject} from '../src/commerce/guided.js';
import {CATALOG} from '../src/commerce/catalog.js';
const d=initialDraft('aruba');
const column=CATALOG.columns.find(c=>c.collection==='aruba');
const project=draftProject({...d,column:!!column,columnModel:column?.id,columnFinish:column?.finishes[0]||d.finish});
project.room={points:[[0,0],[510,0],[510,290],[320,290],[320,410],[0,410]],height:280,partitions:[]};
project.floor={collection:'Creta',color:'caramello',format:'60x120',groutColor:'Ivoire'};
project.layouts={floor:{direction:'vertical',pattern:'third',groutWidth:2}};
project.walls[0]={collection:'Allure',color:'decor',format:'60x120',tiles:{'0:0':'panel-A','1:0':'panel-B'},purchasePrice:'PRIVATE_TILE_PURCHASE_MARKER'};
project.client={email:'PRIVATE_EMAIL_MARKER',name:'PRIVATE_CLIENT_MARKER',codeClient:'PRIVATE_CLIENT_CODE_MARKER'};
project.title='PRIVATE_TITLE_MARKER';project.siteReference='PRIVATE_SITE_MARKER';project.comment='PRIVATE_COMMENT_MARKER';
project.proHT='PRIVATE_PURCHASE_MARKER';project.privateCode='PRIVATE_CODE_MARKER';
project.items[0].settings.purchasePrice='PRIVATE_ITEM_PURCHASE_MARKER';
project.items[0].placement.privateNote='PRIVATE_PLACEMENT_MARKER';
const before=JSON.stringify(project),prompt=buildGeneralPhotorealPrompt(project);
assert.equal(JSON.stringify(project),before,'preparation never edits the project');
assert(!prompt.includes('PRIVATE_'),'no customer, reference-chantier, note or purchase data exported');
assert(prompt.includes('Aruba'),'manufacturer model collection is readable');
assert(prompt.includes(CATALOG.finishes.find(f=>f.id===d.finish).name),'actual manufacturer finish label');
assert(prompt.includes('280')&&prompt.includes('510'),'actual non-default room geometry');
assert(prompt.includes('60x120')&&prompt.includes('third'),'actual selected tile format and layout');
assert(prompt.includes('Allure')&&prompt.includes('ordre exact'),'continuous decorative panels must keep their order');
assert(prompt.includes('\"0:0\": \"panel-A\"')&&prompt.includes('\"1:0\": \"panel-B\"'),'actual ordered decorative cells remain in the brief');
assert(prompt.includes('Ne déplace, ne remplace et n’ajoute aucun objet'),'fidelity constraints prevent extra decoration');
if(column)assert(prompt.includes(column.name),'exact column model has catalogue label');
assert(!prompt.includes('publicTTC')&&!prompt.includes('subtotal')&&!prompt.includes('€'),'no pricing fields in the visual brief');
console.log('General photoreal brief: exact catalogue labels, room/material fidelity, privacy and immutability passed.');
