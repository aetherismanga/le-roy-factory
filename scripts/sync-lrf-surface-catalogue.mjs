// Generate transfer capabilities and PLAN & POSE media fields from the one
// reviewed source. Run after build-lrf-plan-catalogue.cjs; never rewrite images.
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {RAL_COLORS} from '../shared/lrf-3d/ral-colors.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const shared=path.join(root,'shared/lrf-3d'),pp=path.join(root,'assets/js/lrf-plan-pose');
const read=async file=>JSON.parse(await readFile(file,'utf8'));
const manufacturer=await read(path.join(shared,'manufacturer-surfaces.json'));
const revision='lrf-surfaces-20261024-v1';
const collections=manufacturer.map(collection=>{
 const aliases=collection.name==='Sedimenti'?Object.fromEntries(['white','beige','sand','grey'].flatMap(color=>['selected','tumbled'].map(suffix=>[color+suffix,color]))):collection.name==='Bavaria Stone'?{stone:'bavaria-stone'}:{};
 const formats=collection.formats.map(({id,width,height})=>({id,width,height}));
 if(['Roma','Sedimenti'].includes(collection.name))formats.push({id:'Opus · module 4 formats',width:1.218,height:.609});
 return {name:collection.name,brand:collection.brand,surfaces:collection.surfaces,formats,aliases,colors:collection.colors.map(color=>({id:color.id,name:color.name,exportable:color.available3d!==false&&!!color.file,references:Object.entries(color.textureVariantsByReference||{}).filter(([,mapping])=>mapping.verified===true).map(([key])=>key)}))};
});
collections.push({name:'Peinture',brand:'Peinture',surfaces:['wall'],formats:[],aliases:{},colors:[...['white','ivory','sand','sage','clay','grey','dark'].map(id=>({id,name:id,exportable:true,references:[]})),...RAL_COLORS.map(({id,name})=>({id,name,exportable:true,references:[]}))]});
const contract={version:1,catalogueRevision:revision,collections};
await writeFile(path.join(shared,'surface-contract.json'),JSON.stringify(contract)+'\n');
await writeFile(path.join(shared,'surface-contract.mjs'),'// Generated by scripts/sync-lrf-surface-catalogue.mjs.\nexport default '+JSON.stringify(contract)+';\n');
const catalogue=await read(path.join(pp,'catalogue.json')),review=await read(path.join(pp,'catalogue-review.json'));
const byCollection=new Map(manufacturer.map(collection=>[collection.name,collection]));
let enriched=0;
for(const product of [...catalogue.products,...review.products]){
 const collection=byCollection.get(product.collection),definition=collections.find(item=>item.name===product.collection);
 if(!collection||!definition)continue;
 const renderColorId=definition.aliases[product.colorId]||product.colorId,choice=collection.colors.find(color=>color.id===renderColorId);
 if(!choice)continue;
 product.renderColorId=renderColorId;product.catalogueRevision=revision;
 if(choice.available3d===false||!choice.file)continue;
 const candidate=choice.textureVariantsByReference?.[product.reference];
 const mapped=candidate?.verified===true&&(!candidate.format||candidate.format===product.format);
 if(mapped){
  // Existing reviewed native mappings are retained byte-for-byte.
  product.textureVariants??=structuredClone(candidate.textureVariants);
  product.textureRotation=candidate.textureRotation||0;product.textureReference=product.reference;product.nativeFaces=true;
 }else if(choice.textureVariants){
  product.textureVariants=structuredClone(choice.textureVariants);product.textureRotation=choice.textureRotation||0;product.nativeFaces=choice.nativeFaces===true;
 }else if(!product.textureVariants){
  product.faces=structuredClone(choice.faces?.length?choice.faces:[choice.file]);product.nativeFaces=choice.nativeFaces===true;
 }
 product.textureResolution=choice.resolution;product.definitionLimited=choice.definitionLimited===true;product.continuousDecor=choice.continuousDecor===true;
 product.textureSourceKind=mapped?'reference-face':choice.definitionLimited?'catalogue-sample':'manufacturer-face';enriched++;
}
catalogue.catalogueRevision=revision;catalogue.surfaceContractVersion=contract.version;
await writeFile(path.join(pp,'catalogue.json'),JSON.stringify(catalogue,null,2)+'\n');
await writeFile(path.join(pp,'catalogue-review.json'),JSON.stringify(review,null,2)+'\n');
console.log(JSON.stringify({revision,collections:manufacturer.length,enriched,imagesModified:0}));
